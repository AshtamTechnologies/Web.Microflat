export function getRegionName(regionId) {
  if (!regionId) return '—';
  return getPathLabel(regionId, INITIAL_REGIONS, {
    idKey: 'regionId',
    parentKey: 'parentRegionId',
    nameKey: 'regionName',
  });
}

export function getCategoryName(categoryId) {
  const cat = CATEGORY_OPTIONS.find((c) => c.value === categoryId);
  return cat ? cat.label : categoryId || '—';
}

export function getStatusOption(statusId) {
  return STATUS_OPTIONS.find((s) => s.id === statusId) || STATUS_OPTIONS[0];
}

export function getPriorityBadgeVariant(priority) {
  switch (priority) {
    case 'High':
      return 'danger';
    case 'Medium':
      return 'warning';
    case 'Low':
    default:
      return 'neutral';
  }
}

export function formatCurrencyINR(amount) {
  if (amount === undefined || amount === null || amount === '') return '—';
  const num = Number(amount);
  if (isNaN(num)) return amount;
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(num);
}

